"""Record the category and icon of each saved Mapstr place.

For every feature in data/mapstr.json, decides its category (the place itself,
then your tags, then Mapstr's icon; see stede.places.category_for) and its
category's default icon, and writes both back into the file as
`properties.stede`:

    {"category": "museum", "icon": "portico"}

Once recorded, a place keeps its icon: later runs only fill in places that
don't have one yet, so an icon picked by hand is never overwritten. Mapstr's
own `icon` is left as it was. A copy of the file before the first run is kept
next to it as mapstr.json.icons.bak.

Don't run it while scripts/match_osm.py is running: that script rewrites the
whole file as it goes and would drop the icons.

    cd backend
    uv run python scripts/assign_icons.py           # places without an icon
    uv run python scripts/assign_icons.py --redo    # decide every place again
    uv run python scripts/assign_icons.py --dry-run # show what would change
    uv run python scripts/assign_icons.py --file ../data/pindrop.json  # another file
"""

import argparse
import json
import shutil
from collections import Counter
from pathlib import Path

from stede.places import category_for

ROOT = Path(__file__).resolve().parents[2]
PLACES_FILE = ROOT / "data" / "mapstr.json"
# Generated by frontend/scripts/place_icons.py, so both sides pick the same icon.
ICON_CATEGORIES_FILE = ROOT / "frontend" / "src" / "placeIconCategories.json"


def main() -> None:
    global PLACES_FILE
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--file",
        type=Path,
        default=PLACES_FILE,
        help="places file (default: mapstr.json)",
    )
    parser.add_argument(
        "--redo",
        action="store_true",
        help="decide places that already have an icon again",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="count the changes without writing the file",
    )
    args = parser.parse_args()
    PLACES_FILE = args.file.resolve()

    mapping = json.loads(ICON_CATEGORIES_FILE.read_text())
    collection = json.loads(PLACES_FILE.read_text())
    features = collection["features"]

    todo = [
        f
        for f in features
        if args.redo or not (f["properties"].get("stede") or {}).get("icon")
    ]
    icons = Counter()
    for f in todo:
        category = category_for(f["properties"])
        group = mapping["values"].get(category, "other")
        icon = mapping["defaults"][group]
        f["properties"]["stede"] = {"category": category, "icon": icon}
        # A category from the matched OSM element knows its key (amenity…).
        kind = (f["properties"].get("osm") or {}).get("kind")
        if kind and kind[1] == category:
            f["properties"]["stede"]["category_key"] = kind[0]
        icons[icon] += 1

    print(f"{len(todo)} of {len(features)} places decided")
    for icon, count in icons.most_common():
        print(f"  {count:5}  {icon}")
    if args.dry_run or not todo:
        return

    backup = PLACES_FILE.with_suffix(".json.icons.bak")
    if not backup.exists():
        shutil.copy2(PLACES_FILE, backup)
    # Written beside the file, then swapped in, so a crash never leaves it half-written.
    tmp = PLACES_FILE.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(collection, ensure_ascii=False, indent=2))
    shutil.copymode(PLACES_FILE, tmp)
    tmp.replace(PLACES_FILE)
    print(f"written to {PLACES_FILE}")


if __name__ == "__main__":
    main()
